"""Configurações demonstrativas; não altera idioma, inicialização ou instalação reais."""
from pathlib import Path
from PyQt5.QtCore import Qt, pyqtSignal
from PyQt5.QtWidgets import (QCheckBox, QComboBox, QFrame, QHBoxLayout,
                             QMessageBox, QPushButton, QScrollArea, QVBoxLayout, QWidget)
from ui_audio_preview import card
from ui_effects_preview import text


class SettingsPage(QWidget):
    subtitles_changed = pyqtSignal(bool)

    def __init__(self):
        super().__init__()
        layout = QHBoxLayout(self)
        layout.setContentsMargins(0,0,0,0)
        layout.setSpacing(0)
        content = QWidget()
        main = QVBoxLayout(content)
        main.setContentsMargins(24,24,24,16)
        main.setSpacing(14)
        main.addWidget(text('Configurações','heading'))
        main.addWidget(text('Preferências do aplicativo e manutenção em um só lugar.','muted'))
        frame,fields = card('Aplicativo','Estas preferências valem para todos os perfis.')
        fields.addWidget(text('Idioma da interface'))
        self.language = QComboBox()
        self.language.setAccessibleName('Idioma da interface')
        for name,code in [('Automático — idioma do sistema','auto'),('Português','pt'),('English','en')]:
            self.language.addItem(name,code)
        fields.addWidget(self.language)
        fields.addWidget(text('No aplicativo, a mudança se aplica ao reiniciar. Esta prévia permanece em português.','muted'))
        fields.addWidget(text('Ao fechar a janela'))
        self.close_behavior = QComboBox()
        self.close_behavior.setAccessibleName('Comportamento ao fechar a janela')
        self.close_behavior.addItem('Minimizar para a bandeja','tray')
        self.close_behavior.addItem('Encerrar o aplicativo','quit')
        self.close_behavior.setCurrentIndex(1)
        fields.addWidget(self.close_behavior)
        main.addWidget(frame)
        frame,fields = card('Legendas durante a gravação','Esta escolha acompanha o perfil selecionado no topo.')
        self.subtitles = QCheckBox('Exibir legendas ao gravar')
        self.subtitles.setChecked(True)
        self.subtitles.setStyleSheet('background: transparent; padding: 4px 0;')
        self.subtitles.toggled.connect(self.subtitles_changed.emit)
        fields.addWidget(self.subtitles)
        main.addWidget(frame)
        frame,fields = card('Versão e atualizações','Confira novas versões e a opção de inicialização automática.')
        version = (Path(__file__).resolve().parents[1]/'version').read_text().strip()
        fields.addWidget(text('Versão do código: '+version))
        self.update_button = QPushButton('Verificar atualizações')
        self.update_button.clicked.connect(lambda:QMessageBox.information(self,'Atualizações — demonstração','Na integração, esta ação consultará a versão publicada e mostrará a confirmação antes de atualizar. Nesta prévia, nenhuma consulta ou atualização é executada.'))
        fields.addWidget(self.update_button)
        fields.addWidget(text('Iniciar automaticamente ao entrar no sistema','section'))
        fields.addWidget(text('A escolha é oferecida na instalação e na confirmação de uma atualização.','muted'))
        main.addWidget(frame)
        frame,fields = card('Desinstalação','Disponível no aplicativo instalado. Requer confirmação explícita.')
        self.uninstall_button = QPushButton('Desinstalar Baseus Presenter…')
        self.uninstall_button.setStyleSheet('color: #f4b9b9; border-color: #865252;')
        self.uninstall_button.clicked.connect(lambda:QMessageBox.information(self,'Desinstalação — demonstração','Na versão instalada, esta ação abre o desinstalador separado, com confirmação explícita. Em checkouts de desenvolvimento ela fica desativada. Esta prévia não abre processos nem remove arquivos.'))
        fields.addWidget(self.uninstall_button)
        main.addWidget(frame)
        main.addStretch()
        main.addWidget(text('As escolhas são demonstrativas e não alteram seu sistema.','muted'))
        self.scroll = QScrollArea()
        self.scroll.setWidgetResizable(True)
        self.scroll.setHorizontalScrollBarPolicy(Qt.ScrollBarAlwaysOff)
        self.scroll.setFrameShape(QFrame.NoFrame)
        self.scroll.setStyleSheet('QScrollBar:vertical { background: #181b20; width: 10px; margin: 3px; } QScrollBar::handle:vertical { background: #4b5c72; min-height: 30px; border-radius: 2px; } QScrollBar::add-line:vertical, QScrollBar::sub-line:vertical { height: 0px; } QScrollBar::add-page:vertical, QScrollBar::sub-page:vertical { background: transparent; }')
        self.scroll.setWidget(content)
        layout.addWidget(self.scroll,1)
        side = QFrame(objectName='details')
        side.setFixedWidth(306)
        panel = QVBoxLayout(side)
        panel.setContentsMargins(24,28,24,24)
        panel.setSpacing(18)
        panel.addWidget(text('PREFERÊNCIAS E PERFIS','section'))
        panel.addWidget(text('Tudo no seu lugar','heading'))
        panel.addWidget(text('APLICATIVO','section'))
        panel.addWidget(text('Idioma da interface e ação ao fechar a janela são escolhas globais.'))
        panel.addWidget(text('PERFIL SELECIONADO','section'))
        panel.addWidget(text('Efeitos, áudio, tradução e exibição de legendas acompanham cada perfil.'))
        panel.addWidget(text('BATERIA','section'))
        panel.addWidget(text('O cabeçalho mantém a carga do passador visível em qualquer seção. Nesta prévia, o valor é um exemplo.'))
        panel.addStretch()
        panel.addWidget(text('A integração preservará suas configurações, perfis e o ícone atual da bandeja.','muted'))
        layout.addWidget(side)
        for combo in (self.language,self.close_behavior):
            combo.setMinimumHeight(38)
        self.update_button.setMinimumHeight(40)
        self.uninstall_button.setMinimumHeight(40)

    def set_subtitles(self,enabled):
        self.subtitles.blockSignals(True)
        self.subtitles.setChecked(enabled)
        self.subtitles.blockSignals(False)
